import gradio as gr
from deep_translator import GoogleTranslator  # Yahan underscore '_' aayega

# Translation Function
def translate_text(text, source_lang, target_lang):
    if not text.strip():
        return "Please enter text to translate."
    try:
        translated = GoogleTranslator(source=source_lang, target=target_lang).translate(text)
        return translated
    except Exception as e:
        return f"Error: {str(e)}"

# Language Options Mapping
languages = {
    'English': 'en',
    'Urdu': 'ur',
    'Spanish': 'es',
    'French': 'fr',
    'German': 'de',
    'Hindi': 'hi',
    'Arabic': 'ar',
    'Chinese (Simplified)': 'zh-CN'
}

def process_translation(text, src, tgt):
    src_code = languages[src]
    tgt_code = languages[tgt]
    return translate_text(text, src_code, tgt_code)

# Gradio User Interface
interface = gr.Interface(
    fn=process_translation,
    inputs=[
        gr.Textbox(lines=4, placeholder="Enter text here...", label="Input Text"),
        gr.Dropdown(choices=list(languages.keys()), value='English', label="Source Language"),
        gr.Dropdown(choices=list(languages.keys()), value='Urdu', label="Target Language")
    ],
    outputs=gr.Textbox(label="Translated Output"),
    title="CodeAlpha - Language Translation Tool",
    description="Select source and target languages to translate your text easily."
)

# Launch UI inside Colab
interface.launch(share=True)